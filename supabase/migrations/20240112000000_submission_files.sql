-- ============================================================
-- Migration: submission-files storage — one optional student file
--             attached to their own assignment_submissions row.
-- Run once in the Supabase SQL Editor.
-- ============================================================
--
-- Assumptions:
--   public.assignment_submissions exists (from 20240109), including the
--   already-unused attachment_url column and its existing guard trigger,
--   which already:
--     - blocks teachers from ever writing attachment_url
--     - only allows students to write it while status IN ('draft','submitted')
--       (enforced by the existing "Students can update own submissions" RLS
--       UPDATE policy, which requires that status range in both USING and
--       WITH CHECK)
--   No changes to that table, its triggers, or its RLS are made here —
--   this migration only adds the storage bucket and the SECURITY DEFINER
--   helpers needed to gate storage.objects for that bucket.
--
--   public.safe_uuid(text) is defined in 20240111_assignment_files.sql,
--   which runs before this migration — reused here as-is, not redefined.
-- ============================================================

-- ── SECURITY DEFINER helpers ──────────────────────────────────

-- public.owns_submission(submission_id)
--
-- Returns TRUE iff auth.uid() is the student who owns the given submission.
-- SECURITY DEFINER bypasses RLS on assignment_submissions, so evaluating
-- this from a storage.objects policy never re-enters that table's RLS.

CREATE OR REPLACE FUNCTION public.owns_submission(p_submission_id uuid)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM   public.assignment_submissions
    WHERE  id         = p_submission_id
      AND  student_id = auth.uid()
  );
$$;

REVOKE EXECUTE ON FUNCTION public.owns_submission(uuid) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.owns_submission(uuid) TO authenticated;

-- public.teaches_submission(submission_id)
--
-- Returns TRUE iff auth.uid() teaches the class that owns the assignment
-- that the given submission belongs to.

CREATE OR REPLACE FUNCTION public.teaches_submission(p_submission_id uuid)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM   public.assignment_submissions s
    JOIN   public.assignments            a ON a.id = s.assignment_id
    JOIN   public.classes                c ON c.id = a.class_id
    WHERE  s.id           = p_submission_id
      AND  c.teacher_id   = auth.uid()
  );
$$;

REVOKE EXECUTE ON FUNCTION public.teaches_submission(uuid) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.teaches_submission(uuid) TO authenticated;

-- public.can_modify_submission_files(submission_id)
--
-- Returns TRUE iff auth.uid() owns the given submission AND the submission
-- is still editable (status draft/submitted) AND the assignment is still
-- published. This is the write-scope check for submission-files: it must
-- be strictly narrower than owns_submission(), because a student should
-- still be able to *read* a file they attached even after the submission
-- is graded/returned (the existing student-facing UI shows it read-only),
-- but must never be able to upload, replace, move, or delete one once
-- grading has happened or the assignment is unpublished.

CREATE OR REPLACE FUNCTION public.can_modify_submission_files(p_submission_id uuid)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM   public.assignment_submissions s
    JOIN   public.assignments            a ON a.id = s.assignment_id
    WHERE  s.id         = p_submission_id
      AND  s.student_id = auth.uid()
      AND  s.status     IN ('draft', 'submitted')
      AND  a.status     = 'published'
  );
$$;

REVOKE EXECUTE ON FUNCTION public.can_modify_submission_files(uuid) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.can_modify_submission_files(uuid) TO authenticated;

-- ── Storage bucket ────────────────────────────────────────────
-- Private bucket — no public URLs. All reads go through signed URLs
-- generated by an authenticated client, gated by the storage.objects
-- policies below. file_size_limit/allowed_mime_types give bucket-level
-- enforcement (checked by the Storage API itself on upload) in addition
-- to the application's own client-side checks — PDF/PNG/JPEG, 20 MB max.

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'submission-files',
  'submission-files',
  false,
  20971520, -- 20 MB
  ARRAY['application/pdf', 'image/png', 'image/jpeg']
)
ON CONFLICT (id) DO UPDATE
  SET public             = EXCLUDED.public,
      file_size_limit    = EXCLUDED.file_size_limit,
      allowed_mime_types = EXCLUDED.allowed_mime_types;

-- ── Storage RLS ───────────────────────────────────────────────
--
-- Object path convention: "{submission_id}/{uuid}-{original_file_name}".
-- public.safe_uuid((storage.foldername(name))[1]) recovers the
-- submission_id (or NULL for a malformed path — treated as "no match").
--
-- Read access (SELECT) is scoped only to ownership (owns_submission),
-- deliberately unrestricted by status, so a student can still view a file
-- they attached after their submission is graded/returned. Every write
-- action (INSERT/UPDATE/DELETE) is scoped to the strictly narrower
-- can_modify_submission_files, which additionally requires the submission
-- to still be draft/submitted and the assignment to still be published —
-- this is what actually blocks upload/replace/move/delete once grading
-- has happened.

CREATE POLICY "Students can read own submission file objects"
  ON storage.objects FOR SELECT TO authenticated
  USING (
    bucket_id = 'submission-files'
    AND public.owns_submission(public.safe_uuid((storage.foldername(name))[1]))
  );

CREATE POLICY "Students can upload own submission file objects"
  ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'submission-files'
    AND public.can_modify_submission_files(public.safe_uuid((storage.foldername(name))[1]))
  );

CREATE POLICY "Students can replace own submission file objects"
  ON storage.objects FOR UPDATE TO authenticated
  USING (
    bucket_id = 'submission-files'
    AND public.can_modify_submission_files(public.safe_uuid((storage.foldername(name))[1]))
  )
  WITH CHECK (
    bucket_id = 'submission-files'
    AND public.can_modify_submission_files(public.safe_uuid((storage.foldername(name))[1]))
  );

CREATE POLICY "Students can delete own submission file objects"
  ON storage.objects FOR DELETE TO authenticated
  USING (
    bucket_id = 'submission-files'
    AND public.can_modify_submission_files(public.safe_uuid((storage.foldername(name))[1]))
  );

CREATE POLICY "Teachers can read class submission file objects"
  ON storage.objects FOR SELECT TO authenticated
  USING (
    bucket_id = 'submission-files'
    AND public.teaches_submission(public.safe_uuid((storage.foldername(name))[1]))
  );
