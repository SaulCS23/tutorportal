-- ============================================================
-- Migration: assignment_files — teacher-uploaded PDF attachments
-- Run once in the Supabase SQL Editor.
-- ============================================================
--
-- Assumptions:
--   public.assignments               exists (from 20240107)
--   public.is_teacher_of_assignment  exists (from 20240109) — SECURITY DEFINER,
--                                    true iff auth.uid() teaches the class that
--                                    owns the given assignment
--   public.can_student_submit        exists (from 20240109) — SECURITY DEFINER,
--                                    true iff the assignment is published AND
--                                    auth.uid() is enrolled in its class
--
-- Both helpers already encode exactly the checks this table needs, so they
-- are reused as-is for the row-level table policies below.
--
-- This migration also defines public.safe_uuid(text), a small casting
-- helper used by every storage.objects policy in this migration (and in
-- 20240112_submission_files.sql, which runs after this one). Storage path
-- segments are plain text; a direct "::uuid" cast on a malformed segment
-- raises invalid_text_representation and aborts the whole policy check
-- with a hard error instead of simply denying access. safe_uuid() catches
-- that and returns NULL, so a malformed path is treated as "no match" —
-- every downstream helper already returns false for a NULL id argument.
-- ============================================================

-- ── Helpers ───────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.safe_uuid(p_text text)
RETURNS uuid
LANGUAGE plpgsql
SET search_path = public
IMMUTABLE
AS $$
BEGIN
  RETURN p_text::uuid;
EXCEPTION WHEN invalid_text_representation THEN
  RETURN NULL;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.safe_uuid(text) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.safe_uuid(text) TO authenticated;

-- ── Table ─────────────────────────────────────────────────────

CREATE TABLE public.assignment_files (
  id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id  uuid        NOT NULL REFERENCES public.assignments(id) ON DELETE CASCADE,

  storage_path   text        NOT NULL UNIQUE,
  file_name      text        NOT NULL,
  mime_type      text        NOT NULL,
  file_size      bigint      NOT NULL,

  -- Defaults to the calling user so the client never needs to (and cannot
  -- usefully) supply this column — mirrors assignment_submissions.student_id.
  uploaded_by    uuid        NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,

  created_at     timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT assignment_files_size_positive CHECK (file_size > 0)
);

-- Files are immutable — delete and re-upload instead of editing in place,
-- so there is no updated_at column and no UPDATE policy/grant below.

-- ── Indexes ───────────────────────────────────────────────────

CREATE INDEX assignment_files_assignment_id_idx ON public.assignment_files(assignment_id);

-- ── RLS ───────────────────────────────────────────────────────

ALTER TABLE public.assignment_files ENABLE ROW LEVEL SECURITY;

-- Teachers: full management of files on assignments in their own classes.
-- WITH CHECK also pins uploaded_by to the caller — uploaded_by defaults to
-- auth.uid(), but without this check a teacher could still explicitly send
-- a different profile id in the INSERT payload and misattribute a file.
CREATE POLICY "Teachers can manage own assignment files"
  ON public.assignment_files FOR ALL TO authenticated
  USING    (public.is_teacher_of_assignment(assignment_id))
  WITH CHECK (
    public.is_teacher_of_assignment(assignment_id)
    AND uploaded_by = auth.uid()
  );

-- Students: read-only, and only for published assignments in classes they're
-- enrolled in — can_student_submit already encodes both conditions.
CREATE POLICY "Students can read published assignment files"
  ON public.assignment_files FOR SELECT TO authenticated
  USING (public.can_student_submit(assignment_id));

-- ── Grants ────────────────────────────────────────────────────
-- No UPDATE: files are immutable. No DELETE grant for students.

GRANT SELECT, INSERT, DELETE ON public.assignment_files TO authenticated;

-- ── Storage bucket ────────────────────────────────────────────
-- Private bucket — no public URLs. All reads go through signed URLs
-- generated by an authenticated client, gated by the storage.objects
-- policies below. file_size_limit/allowed_mime_types give bucket-level
-- enforcement (checked by the Storage API itself on upload) in addition
-- to the application's own client-side checks — PDF only, 20 MB max.

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'assignment-files',
  'assignment-files',
  false,
  20971520, -- 20 MB
  ARRAY['application/pdf']
)
ON CONFLICT (id) DO UPDATE
  SET public             = EXCLUDED.public,
      file_size_limit    = EXCLUDED.file_size_limit,
      allowed_mime_types = EXCLUDED.allowed_mime_types;

-- ── Storage RLS ───────────────────────────────────────────────
--
-- Object path convention: "{assignment_id}/{uuid}-{original_file_name}".
-- storage.foldername(name) returns the path segments before the final
-- component; public.safe_uuid(...) recovers the assignment_id the object
-- belongs to (or NULL for a malformed path, which every helper below
-- treats as "no match" rather than raising a cast error).

CREATE POLICY "Teachers can manage own assignment file objects"
  ON storage.objects FOR ALL TO authenticated
  USING (
    bucket_id = 'assignment-files'
    AND public.is_teacher_of_assignment(public.safe_uuid((storage.foldername(name))[1]))
  )
  WITH CHECK (
    bucket_id = 'assignment-files'
    AND public.is_teacher_of_assignment(public.safe_uuid((storage.foldername(name))[1]))
  );

CREATE POLICY "Students can read published assignment file objects"
  ON storage.objects FOR SELECT TO authenticated
  USING (
    bucket_id = 'assignment-files'
    AND public.can_student_submit(public.safe_uuid((storage.foldername(name))[1]))
  );
